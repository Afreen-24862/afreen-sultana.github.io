/* Code walkthrough: each project as a flow of modules.
   Click a module -> what it does, the key code, and the output it produced.
   "Detailed" shows the full, commented source file.
   Data comes from js/codelab-data.js (generated by tools/build_codelab.py). */
(() => {
  const $ = (s, r = document) => r.querySelector(s), $$ = (s, r = document) => [...r.querySelectorAll(s)];
  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const BLOB = 'https://github.com/Afreen-24862/afreen-sultana.github.io/blob/main/';
  const reduce = matchMedia('(prefers-reduced-motion:reduce)').matches;
  const root = $('#codelab'); if (!root) return;

  let D = null, P = null, mi = 0, view = 'key', runToken = 0, pending = null;
  const toast = m => { const t = $('#toast'); if (!t) return; t.textContent = m; t.classList.add('on'); clearTimeout(toast.t); toast.t = setTimeout(() => t.classList.remove('on'), 2000); };
  const fmtDate = iso => new Date(iso + 'T00:00:00').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });

  /* ---------- load data lazily (only when the section is near) ---------- */
  const load = () => new Promise((ok, fail) => {
    if (window.CODELAB) return ok(window.CODELAB);
    const s = document.createElement('script'); s.src = 'js/codelab-data.js'; s.onload = () => ok(window.CODELAB); s.onerror = fail; document.head.appendChild(s);
  });
  const start = () => load().then(d => { D = d; renderShell(); selectProject(pending || D.projects[0].id); }).catch(() => { root.innerHTML = '<p class="cl-loading">Could not load the code walkthrough.</p>'; });
  if ('IntersectionObserver' in window) new IntersectionObserver((es, o) => { if (es[0].isIntersecting) { o.disconnect(); start(); } }, { rootMargin: '700px' }).observe(root); else start();

  // scroll a horizontal strip so the item is centred - never moves the page
  const centerX = (strip, item) => { if (!strip || !item) return; strip.scrollTo({ left: item.offsetLeft - (strip.clientWidth - item.clientWidth) / 2, behavior: reduce ? 'auto' : 'smooth' }); };

  /* ---------- shell: project tabs + project area ---------- */
  function renderShell() {
    root.innerHTML = `<div class="cl-tabs" role="tablist" aria-label="Projects">${D.projects.map(p => `<button role="tab" data-p="${p.id}" aria-selected="false">${esc(p.name)}${p.badge ? `<small>${esc(p.badge)}</small>` : ''}</button>`).join('')}</div><div class="cl-proj" id="clProj"></div>`;
    $('.cl-tabs', root).onclick = e => { const b = e.target.closest('[data-p]'); if (b) selectProject(b.dataset.p); };
  }

  function selectProject(id) {
    P = D.projects.find(p => p.id === id) || D.projects[0]; mi = 0; view = 'key'; runToken++;
    $$('.cl-tabs [data-p]', root).forEach(b => b.setAttribute('aria-selected', b.dataset.p === P.id));
    centerX($('.cl-tabs', root), $(`.cl-tabs [data-p="${P.id}"]`, root));
    const runnable = P.modules.some(m => m.ran);
    $('#clProj').innerHTML = `
      <div class="cl-head">
        <div><h3>${esc(P.name)} <em>— ${esc(P.sub)}</em></h3><p class="cl-data"><b>Data</b> ${esc(P.data)}</p>
          <div class="cl-stack">${P.stack.map(s => `<span>${esc(s)}</span>`).join('')}</div></div>
        <div class="cl-meta"><span>${P.modules.length} modules · ${P.loc.toLocaleString()} lines</span>
          ${runnable ? `<span>Outputs captured ${fmtDate(D.generated)} · Python ${esc(D.python)}</span>` : '<span>Code + screenshots from the running app</span>'}
          <div class="cl-acts">${runnable ? '<button class="btn solid cl-runall" type="button">▶ Run all steps</button>' : ''}<a class="btn ghost" href="${P.folder}" target="_blank" rel="noopener">Source folder ↗</a></div></div>
      </div>
      <div class="cl-kpis">${P.kpis.map(k => `<div><b>${esc(k.v)}</b><span>${esc(k.l)}</span></div>`).join('')}</div>
      <ol class="cl-flow" aria-label="Pipeline steps">${P.modules.map((m, i) => `<li><button class="cl-node" data-i="${i}" aria-current="false"><i>${i + 1}</i><b>${esc(m.title)}</b><code>${esc(m.file ? m.file.split('/').pop() : 'UI screens')}</code></button></li>`).join('')}</ol>
      <div class="cl-step" id="clStep" aria-live="polite"></div>`;
    $('.cl-flow', root).onclick = e => { const b = e.target.closest('.cl-node'); if (b) { runToken++; selectModule(+b.dataset.i, { scroll: false }); } };
    $('.cl-flow', root).onkeydown = e => { if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return; e.preventDefault(); const n = Math.max(0, Math.min(P.modules.length - 1, mi + (e.key === 'ArrowRight' ? 1 : -1))); runToken++; selectModule(n); $$('.cl-node', root)[n].focus(); };
    const ra = $('.cl-runall', root); if (ra) ra.onclick = runAll;
    selectModule(0, { scroll: false });
  }

  /* ---------- one module: description + code + output ---------- */
  function selectModule(i, { scroll = true, animate = false } = {}) {
    mi = i; view = 'key'; const m = P.modules[i];
    $$('.cl-node', root).forEach((b, k) => { b.setAttribute('aria-current', k === i ? 'step' : 'false'); b.classList.toggle('done', k < i); });
    centerX($('.cl-flow', root), $$('.cl-node', root)[i].parentNode);
    const hasCode = !!m.code, hasOut = m.out != null || m.imgs.length || m.preview;
    const outLabel = m.ran ? 'Execution output' : m.preview ? 'UI preview' : 'Output · screenshot from the running app';
    $('#clStep').innerHTML = `
      <div class="cl-step-h">
        <div><small>STEP ${i + 1} OF ${P.modules.length}${m.file ? ` · <code>${esc(m.file)}</code>` : ''}</small><h4>${esc(m.title)}</h4><p>${esc(m.does)}</p></div>
        ${m.notes && m.notes.length ? `<div class="cl-notes"><small>Say it in the interview</small><ul>${m.notes.map(n => `<li>${esc(n)}</li>`).join('')}</ul></div>` : ''}
      </div>
      <div class="cl-panes${hasCode ? '' : ' wide'}">
        ${hasCode ? `<div class="cl-code">
          <div class="cl-bar"><span class="cl-fn">${esc(m.file.split('/').pop())}</span>
            <div class="cl-seg" role="group" aria-label="Code view">${m.key ? '<button data-v="key" aria-pressed="true">Key part</button>' : ''}<button data-v="full" aria-pressed="${m.key ? 'false' : 'true'}">Detailed · full code</button></div>
            <span class="cl-tools"><button class="cl-copy" type="button" title="Copy full file">Copy</button><a href="${BLOB + m.path}" target="_blank" rel="noopener" title="Open on GitHub">↗</a></span></div>
          <pre class="cl-pre" tabindex="0"><code></code></pre>
          <div class="cl-foot"></div>
        </div>` : ''}
        ${hasOut ? `<div class="cl-out">
          <div class="cl-bar"><span class="cl-cmd">${esc(outLabel)}</span>${m.ran ? '<button class="cl-run" type="button">▶ Run</button>' : ''}</div>
          ${m.ran ? `<pre class="cl-term" tabindex="0"></pre>` : ''}
          ${m.preview ? `<div class="cl-preview">${m.preview}</div><p class="cl-note">Preview filled with this step's real <code>recommend()</code> output. Launch the actual app with <code>${esc(m.cmd)}</code>.</p>` : ''}
          ${m.imgs.length ? `<div class="cl-imgs${m.imgs.length > 2 ? ' grid' : ''}">${m.imgs.map(g => `<figure><a href="${g.src}" target="_blank" rel="noopener"><img src="${g.src}" alt="${esc(g.cap)}" loading="lazy"></a><figcaption>${esc(g.cap)}</figcaption></figure>`).join('')}</div>` : ''}
          ${m.ran ? `<div class="cl-status" hidden>✓ exit 0 · finished in ${m.secs.toFixed(2)} s</div>` : ''}
        </div>` : ''}
      </div>
      <div class="cl-nav"><button class="cl-prev" type="button" ${i ? '' : 'disabled'}>← ${i ? esc(P.modules[i - 1].title) : 'Previous'}</button><button class="cl-next" type="button" ${i < P.modules.length - 1 ? '' : 'disabled'}>${i < P.modules.length - 1 ? esc(P.modules[i + 1].title) : 'Next'} →</button></div>`;

    if (hasCode) { view = m.key ? 'key' : 'full'; drawCode(); }
    if (m.ran) { animate ? null : showOutput(m, false); const r = $('.cl-run', root); r.onclick = () => { runToken++; showOutput(m, true, runToken); }; }
    $('.cl-seg', root) && ($('.cl-seg', root).onclick = e => { const b = e.target.closest('[data-v]'); if (!b) return; view = b.dataset.v; drawCode(); if (view === 'full') toKey(); });
    $('.cl-copy', root) && ($('.cl-copy', root).onclick = () => { const t = document.createElement('div'); t.innerHTML = m.code.join('\n'); navigator.clipboard?.writeText(t.textContent).then(() => toast('Code copied ✓'), () => toast('Copy failed')); });
    $('.cl-prev', root).onclick = () => { runToken++; selectModule(mi - 1); };
    $('.cl-next', root).onclick = () => { runToken++; selectModule(mi + 1); };
    if (scroll) $('#clStep').scrollIntoView({ block: 'nearest', behavior: reduce ? 'auto' : 'smooth' });
  }

  // scroll the code box (not the page) to the highlighted key part
  const toKey = () => { const pre = $('.cl-pre', root), kl = $('.cl-pre .cl-hl', root); if (pre && kl) pre.scrollTop = Math.max(0, kl.offsetTop - 40); };

  function drawCode() {
    const m = P.modules[mi], pre = $('.cl-pre', root), code = $('code', pre);
    const [a, b] = m.key || [1, m.code.length];
    const lines = view === 'key' ? m.code.slice(a - 1, b) : m.code, first = view === 'key' ? a : 1;
    code.innerHTML = lines.map((h, k) => { const n = first + k, isKey = m.key && view === 'full' && n >= a && n <= b; return `<span class="cl-l${isKey ? ' cl-hl' : ''}" data-n="${n}">${h || ' '}</span>`; }).join('');
    pre.classList.toggle('full', view === 'full'); pre.scrollTop = 0;
    $('.cl-panes', root).classList.toggle('det', view === 'full');   // detailed = full-width code
    $$('.cl-seg [data-v]', root).forEach(x => x.setAttribute('aria-pressed', x.dataset.v === view));
    $('.cl-foot', root).innerHTML = view === 'key'
      ? `Key part · lines ${a}–${b} of ${m.lines} <button type="button" class="cl-full">Show detailed full code (${m.lines} lines) →</button>`
      : `Full file · ${m.lines} lines${m.key ? ` · key part highlighted <button type="button" class="cl-keyonly">Back to key part</button>` : ''}`;
    const f = $('.cl-full', root), k = $('.cl-keyonly', root);
    if (f) f.onclick = () => { view = 'full'; drawCode(); toKey(); };
    if (k) k.onclick = () => { view = 'key'; drawCode(); };
  }

  /* ---------- output: instant, or typed out like a terminal ---------- */
  function showOutput(m, animate, token) {
    const term = $('.cl-term', root), status = $('.cl-status', root), imgs = $('.cl-imgs', root), cmd = `<span class="p">$</span> ${esc(m.cmd)}\n`;
    if (!term) return Promise.resolve();
    if (!animate || reduce) { term.innerHTML = cmd + esc(m.out); status.hidden = false; if (imgs) imgs.classList.remove('wait'); return Promise.resolve(); }
    const lines = m.out.split('\n'); term.innerHTML = cmd; status.hidden = true; if (imgs) imgs.classList.add('wait');
    const btn = $('.cl-run', root); btn.disabled = true; btn.textContent = 'Running…';
    let k = 0, per = Math.max(1, Math.ceil(lines.length / 45));
    return new Promise(done => { const tick = () => {
      if (token !== runToken || !term.isConnected) return done();
      term.insertAdjacentHTML('beforeend', esc(lines.slice(k, k + per).join('\n')) + '\n'); k += per; term.scrollTop = term.scrollHeight;
      if (k < lines.length) setTimeout(tick, 28); else { status.hidden = false; if (imgs) imgs.classList.remove('wait'); btn.disabled = false; btn.textContent = '▶ Run again'; done(); }
    }; setTimeout(tick, 240); });
  }

  async function runAll() {
    const btn = $('.cl-runall', root), my = ++runToken;
    if (btn.dataset.on) { delete btn.dataset.on; btn.textContent = '▶ Run all steps'; runToken++; return; }
    btn.dataset.on = 1; btn.textContent = '■ Stop';
    for (let i = 0; i < P.modules.length; i++) {
      if (my !== runToken) break;
      selectModule(i, { animate: true });
      const m = P.modules[i];
      if (m.ran) { await showOutput(m, true, my); }
      if (my !== runToken) break;
      await new Promise(r => setTimeout(r, 900));
    }
    if (btn.isConnected) { delete btn.dataset.on; btn.textContent = '▶ Run all steps'; }
  }

  /* ---------- open from elsewhere (project popup) ---------- */
  window.CodeLab = {
    open(id) {
      const go = () => { (window.lenis ? lenis.scrollTo('#code', { offset: -50 }) : $('#code').scrollIntoView({ behavior: 'smooth' })); };
      if (D) { selectProject(id); go(); } else { pending = id; go(); }
    },
    has: id => ['aira', 'cityair', 'student', 'reelpick', 'resume'].includes(id)
  };
})();
